/**
 * 根据 src/data/products.js 生成产品详情页：src/products/<id>.md
 *
 * 用法：npm run gen（npm run dev / npm run build 会自动执行）
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const DATA_FILE = join(ROOT, 'src/data/products.js')
const OUT_DIR = join(ROOT, 'src/products')
const MARKER = '<!-- AUTO-GENERATED by scripts/gen-products.mjs, do not edit -->'

const escapeYaml = (s) => JSON.stringify(String(s).replace(/\n/g, ' '))

export async function generateProducts({ quiet = false } = {}) {
  if (!existsSync(DATA_FILE)) throw new Error(`[gen] 找不到数据文件：${DATA_FILE}`)

  const { products } = await import(`${pathToFileURL(DATA_FILE).href}?t=${Date.now()}`)

  if (!Array.isArray(products) || products.length === 0) {
    throw new Error('[gen] src/data/products.js 中没有找到 products 数组')
  }

  mkdirSync(OUT_DIR, { recursive: true })

  const ids = new Set()
  const problems = []
  for (const p of products) {
    if (!p.id || !/^[a-z0-9][a-z0-9-]*$/.test(p.id)) {
      problems.push(`id 非法（需小写字母/数字/连字符）：${p.id ?? '(空)'}`)
    }
    if (!p.model || !p.name || !p.category || !p.status) {
      problems.push(`产品 ${p.id} 缺少必填字段（model / name / category / status）`)
    }
    if (ids.has(p.id)) problems.push(`id 重复：${p.id}`)
    ids.add(p.id)
  }
  if (problems.length) {
    throw new Error(`[gen] 数据校验失败：\n  - ${problems.join('\n  - ')}`)
  }

  for (const p of products) {
    const content = `---
title: ${escapeYaml(`${p.model} · ${p.name}`)}
layout: page
pageClass: pm-detail-page
sidebar: false
aside: false
outline: false
editLink: false
lastUpdated: false
---

${MARKER}

<ProductDetail id="${p.id}" />
`
    writeFileSync(join(OUT_DIR, `${p.id}.md`), content, 'utf8')
  }

  let removed = 0
  for (const file of readdirSync(OUT_DIR)) {
    if (!file.endsWith('.md') || file === 'index.md') continue
    const id = file.slice(0, -3)
    if (ids.has(id)) continue
    const full = join(OUT_DIR, file)
    if (readFileSync(full, 'utf8').includes(MARKER)) {
      unlinkSync(full)
      removed++
    }
  }

  if (!quiet) {
    console.log(
      `[gen] 已生成 ${products.length} 个产品详情页${removed ? `，清理 ${removed} 个过期页面` : ''}`,
    )
  }

  return { count: products.length, removed }
}

const isCli = process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url
if (isCli) {
  try {
    await generateProducts()
  } catch (err) {
    console.error(err.message)
    process.exit(1)
  }
}
